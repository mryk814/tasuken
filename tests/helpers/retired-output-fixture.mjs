// retired-output-cleanup の試験の部品。前の版の AI Pack と日別 Context が同期先に置いた形を、
// 一時フォルダーに作る（前の版の書き出し処理は git の 236fb8d4^ と 2445e1e4^ にある）。
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { markdownSignature } from "../../src/shared/canonicalMarkdown.mjs";
import {
  buildThemeFolderManifest,
  THEME_FOLDER_MANIFEST,
} from "../../src/shared/storageResolver.mjs";

export const AI_PACK_FILES = [
  "00 Theme Overview.md",
  "01 Current Work.md",
  "02 Decisions.md",
  "03 Meetings.md",
  "04 Procedures.md",
  "05 Knowledge.md",
  "06 Activity.md",
];
const GENERATED =
  "> Generated by Tasken — read-only projection. Edit the canonical Tasken entity, not this file.";
export const OPERATION_ID = "0f0e0d0c-0b0a-4908-8706-050403020100";

export function fixture() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "tasken-retired-output-"));
  const trashDirectory = path.join(root, "trash");
  fs.mkdirSync(trashDirectory);
  const trashed = [];
  // shell.trashItem の代わり。消した物を見返せるよう、一時のごみ箱へ移す。
  const trash = async (filePath) => {
    trashed.push(path.relative(root, filePath).replace(/\\/g, "/"));
    fs.renameSync(filePath, path.join(trashDirectory, String(trashed.length)));
  };
  return {
    root,
    trashed,
    trash,
    close: () => fs.rmSync(root, { recursive: true, force: true }),
  };
}

export function write(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
}

export function writeThemeFolder(folder, themeId) {
  write(
    path.join(folder, THEME_FOLDER_MANIFEST),
    `${JSON.stringify(buildThemeFolderManifest({ themeId, displayName: "Materials" }))}\n`,
  );
}

/** 前の版の publishThemeAiPack が置いた形：7 ファイルと、その hash を持つ manifest。 */
export function writeAiPack(themeFolder, themeId) {
  const directory = path.join(themeFolder, "AI Pack");
  const files = AI_PACK_FILES.map((name) => {
    const content = `# ${name}\n\n${GENERATED}\n\n本文 ${name}\n`;
    write(path.join(directory, name), content);
    return { name, contentHash: markdownSignature(content), includedEntityIds: [] };
  });
  write(
    path.join(directory, ".tasken-ai-pack.json"),
    `${JSON.stringify({ schema: "tasken-ai-pack/v1", themeId, contentHash: "x", files }, null, 2)}\n`,
  );
  return directory;
}

/** 前の版の publishDailyContext が置いた形：Days/索引/本文と、その hash を持つ manifest。 */
export function writeDailyContext(root, workspaceId) {
  const directory = path.join(root, "Tasken Context");
  const contents = {
    "Days/2026-10-01.md": `# 2026-10-01\n\n${GENERATED}\n`,
    "README.md": "# Tasken Context\n",
    "Weeks/2026-W40.md": "# 2026-W40\n",
    "Months/2026-10.md": "# 2026-10\n",
    "Years/2026.md": "# 2026\n",
    "Sources/README.md": "# Sources\n",
    [`Sources/note-${"a".repeat(64)}.md`]: "# 公開した本文\n",
    [`Sources/Themes/${"b".repeat(64)}.md`]: "# Theme の本文索引\n",
  };
  for (const [relativePath, content] of Object.entries(contents))
    write(path.join(directory, ...relativePath.split("/")), content);
  const hash = (name) => markdownSignature(contents[name]);
  const manifest = {
    schema: "tasken-daily-context/v1",
    workspaceId,
    timezone: "Asia/Tokyo",
    days: {
      "2026-10-01": { relativePath: "Days/2026-10-01.md", contentHash: hash("Days/2026-10-01.md") },
    },
    indexFiles: Object.fromEntries(
      Object.keys(contents)
        .filter((name) => !name.startsWith("Days/"))
        .map((name) => [name, hash(name)]),
    ),
    pending: null,
    operationId: OPERATION_ID,
  };
  write(path.join(directory, ".tasken-context.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  // 前の版の書き込みが途中で残した退避（中身は前の版が書いた README と同じ）。
  write(path.join(directory, `.README.md.${OPERATION_ID}.bak`), contents["README.md"]);
  return directory;
}
